package com.wanderingnomad.sim;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonPrimitive;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;

/**
 * Test vectors shared with the website's TypeScript copy of the sim (web/src/engine). Each case
 * plays a seed through a script of events (standing somewhere, crossing, diaries, Sailing) and
 * records the circles every hour, every log line and the final saved state. The Java test and the
 * web test both replay the script and must match the file exactly.
 *
 * <p>Regenerate after a rules change with: {@code java ... com.wanderingnomad.sim.SharedVectors}
 */
public final class SharedVectors
{
    static final Path FILE = Paths.get("web", "src", "engine", "vectors.json");
    static final int[] SEEDS = {1, 482913, 20261027, -7, 314};
    static final int MINUTES = 1500;
    static final int VOYAGE_SEED = 314;

    private SharedVectors()
    {
    }

    public static void main(String[] args) throws IOException
    {
        Files.write(FILE, (generate() + "\n").getBytes(StandardCharsets.UTF_8));
        System.out.println("Wrote " + FILE.toAbsolutePath());
    }

    static String generate()
    {
        JsonArray cases = new JsonArray();
        for (int seed : SEEDS)
        {
            cases.add(play(seed, script(seed)));
        }
        JsonObject root = new JsonObject();
        root.addProperty("about", "Generated by SharedVectors.java. Both the plugin and the website must reproduce it exactly.");
        root.add("cases", cases);
        return new GsonBuilder().setPrettyPrinting().create().toJson(root);
    }

    /** The events for a seed. Coordinates are worked out once here and then stored, so both sides replay the same ones. */
    static JsonArray script(int seed)
    {
        // Left alone, this seed's Main circle boards a boat, which covers voyages and docking.
        if (seed == VOYAGE_SEED) return new JsonArray();
        NomadSim probe = NomadSim.start(seed);
        for (int i = 0; i < 240; i++) probe.step(null);
        Circle m = probe.main();
        JsonArray events = new JsonArray();
        events.add(event(120, "diary", "misthalin", 3));
        // Step outside Main for half an hour, then back to "unknown".
        events.add(event(240, "player", (int) Math.round(m.x + m.radius + 20), (int) Math.round(m.y)));
        events.add(event(270, "player"));
        for (int t = 90; t < MINUTES; t += 90) events.add(event(t, "cross"));
        events.add(event(600, "sailing", true));
        events.add(event(700, "diary", "kandarin", 5));
        events.add(event(900, "player", 3000, 3300));
        events.add(event(1200, "diary", "misthalin", 1));
        return events;
    }

    private static JsonObject event(int at, String kind, Object... args)
    {
        JsonObject e = new JsonObject();
        e.addProperty("at", at);
        e.addProperty("kind", kind);
        JsonArray a = new JsonArray();
        for (Object o : args)
        {
            if (o instanceof Number) a.add(new JsonPrimitive((Number) o));
            else if (o instanceof Boolean) a.add(new JsonPrimitive((Boolean) o));
            else a.add(new JsonPrimitive(o.toString()));
        }
        e.add("args", a);
        return e;
    }

    static JsonObject play(int seed, JsonArray events)
    {
        NomadSim sim = NomadSim.start(seed);
        Tile player = null;
        JsonArray log = new JsonArray();
        JsonArray hours = new JsonArray();
        for (int minute = 0; minute < MINUTES; minute++)
        {
            for (JsonElement el : events)
            {
                JsonObject e = el.getAsJsonObject();
                if (e.get("at").getAsInt() != minute) continue;
                JsonArray a = e.getAsJsonArray("args");
                String line = null;
                switch (e.get("kind").getAsString())
                {
                    case "player":
                        player = a.size() == 0 ? null : new Tile(a.get(0).getAsInt(), a.get(1).getAsInt());
                        break;
                    case "cross":
                        for (int i = 0; i < sim.circles().size() && line == null; i++) line = sim.crossTo(i, null);
                        break;
                    case "diary":
                        line = sim.setDiaryTiers(a.get(0).getAsString(), a.get(1).getAsInt());
                        break;
                    case "sailing":
                        sim.setSailingUnlocked(a.get(0).getAsBoolean());
                        break;
                    default:
                        throw new IllegalArgumentException(e.toString());
                }
                if (line != null) log.add(entry(minute, line));
            }
            List<String> lines = sim.step(player);
            for (String line : lines) log.add(entry(minute, line));
            if (sim.minutes() % 60 == 0) hours.add(snapshot(sim));
        }
        JsonObject out = new JsonObject();
        out.addProperty("seed", seed);
        out.addProperty("minutes", MINUTES);
        out.add("events", events);
        out.add("hours", hours);
        out.add("log", log);
        out.add("final", new Gson().toJsonTree(sim));
        return out;
    }

    private static JsonArray entry(int minute, String line)
    {
        JsonArray a = new JsonArray();
        a.add(minute);
        a.add(line);
        return a;
    }

    private static JsonObject snapshot(NomadSim sim)
    {
        JsonObject s = new JsonObject();
        s.addProperty("minute", sim.minutes());
        s.addProperty("bound", sim.boundIndex());
        s.addProperty("rngState", sim.rngState);
        JsonArray circles = new JsonArray();
        for (Circle c : sim.circles())
        {
            JsonArray a = new JsonArray();
            a.add(c.x);
            a.add(c.y);
            a.add(c.radius);
            a.add(c.heading);
            circles.add(a);
        }
        s.add("circles", circles);
        return s;
    }
}
